import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page = await browser.newPage();
const errors=[];
page.setDefaultTimeout(15000);
page.on('pageerror',error=>errors.push(error.message));
try {
 await page.goto(process.env.KEYBOARD_TEST_URL || 'http://127.0.0.1:5011/', {waitUntil:'domcontentloaded', timeout:60000});
 const from=page.getByTestId('select-from-warehouse');
 await from.click(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Tab');
 await expect(page.getByTestId('select-to-warehouse')).toBeFocused();
 await expect(from).toContainText('Depósito origen');
 await page.getByTestId('input-transfer-qty-0').fill('7');
 await page.getByTestId('btn-add-transfer-row').click();
 await expect(page.getByTestId('row-transfer-item-1').getByRole('combobox')).toBeFocused();
 await page.getByTestId('btn-remove-transfer-row-1').click();
 await expect(page.getByTestId('row-transfer-item-0').getByRole('combobox')).toBeFocused();
 await expect(page.getByTestId('input-transfer-qty-0')).toHaveValue('7');
 console.log('PASS transferencia: TAB, filas y cantidades');
 await page.getByRole('button',{name:'purchase',exact:true}).click();
 const supplier=page.getByTestId('select-supplier');
 await supplier.fill('ficticio'); await supplier.press('Tab');
 await expect(page.getByTestId('input-proveedor-nombre')).toBeFocused();
 await expect(supplier).toHaveValue('ficticio');
 await supplier.click(); await supplier.press('ArrowUp'); await page.keyboard.press('Enter');
 await expect(supplier).toHaveValue('Proveedor ficticio');
 console.log('PASS compras: búsqueda preservada, TAB y selección explícita');
 await page.getByRole('button',{name:'guest',exact:true}).click();
 const guest=page.getByRole('combobox').first();
 await guest.fill('Cliente'); await page.getByTestId('guest-search-combobox-result-fake-guest').waitFor();
 await guest.press('Tab'); await expect(page.getByLabel('Cantidad')).toBeFocused();
 await expect(guest).toHaveValue('Cliente');
 await guest.click(); await guest.press('ArrowDown'); await guest.press('Enter');
 await expect(page.getByRole('button',{name:'Quitar cliente seleccionado'})).toBeFocused();
 await page.keyboard.press('Enter'); await expect(page.getByRole('combobox').first()).toBeFocused();
 console.log('PASS clientes: TAB, selección y retorno del foco');
 await page.getByRole('button',{name:'dialogs',exact:true}).click();
 await page.getByRole('button',{name:'Abrir modal',exact:true}).click();
 const unit=page.getByRole('combobox',{name:'Unidad'});
 await unit.click(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Escape');
 await expect(unit).toBeFocused(); await expect(page.getByRole('heading',{name:'Modal principal'})).toBeVisible();
 await unit.click(); await page.keyboard.press('Tab');
 await expect(page.getByRole('button',{name:'Abrir anidado'})).toBeFocused();
 await page.keyboard.press('Enter'); await page.getByRole('heading',{name:'Modal anidado'}).waitFor();
 await page.keyboard.press('Escape'); await expect(page.getByRole('button',{name:'Abrir anidado'})).toBeFocused();
 await page.keyboard.press('Escape'); await expect(page.getByRole('button',{name:'Abrir modal',exact:true})).toBeFocused();
 console.log('PASS diálogos: Escape del Select, TAB y retorno anidado');
 expect(await page.locator('body').getAttribute('data-attempted-write')).toBeNull();
 expect(errors).toEqual([]);
 console.log('PASS sin escrituras ni excepciones de página');
} finally { await browser.close(); }
